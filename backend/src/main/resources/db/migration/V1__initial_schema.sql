-- Fuzzy search on listing titles (replaces Django's TrigramSimilarity)
CREATE EXTENSION IF NOT EXISTS pg_trgm;


-- ---------------------------------------------------------------------
-- Users  ("user" is a reserved word in PostgreSQL, hence "users")
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,          -- bcrypt hash, never plain text
    first_name     VARCHAR(150),
    last_name      VARCHAR(150),
    role           VARCHAR(20)  NOT NULL DEFAULT 'user'
                   CHECK (role IN ('user', 'admin')),
    postal_code    VARCHAR(5)
                   CHECK (postal_code ~ '^[0-9]{5}$'),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);


-- ---------------------------------------------------------------------
-- Listings (offers or requests of time)
-- ---------------------------------------------------------------------
CREATE TABLE listing (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    description       TEXT         NOT NULL,
    type              VARCHAR(10)  NOT NULL DEFAULT 'offer'
                      CHECK (type IN ('offer', 'request')),
    status            VARCHAR(20)  NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'active', 'closed')),
    duration_minutes  INTEGER      CHECK (duration_minutes > 0),
    author_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    requester_id      BIGINT                REFERENCES users (id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_listing_author     ON listing (author_id);
CREATE INDEX idx_listing_requester  ON listing (requester_id);
CREATE INDEX idx_listing_status     ON listing (status);
CREATE INDEX idx_listing_title_trgm ON listing USING gin (title gin_trgm_ops);


-- ---------------------------------------------------------------------
-- Discussions
-- ---------------------------------------------------------------------
CREATE TABLE discussion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  BIGINT UNIQUE REFERENCES listing (id) ON DELETE CASCADE
);

-- Which users take part in which discussion (was UserDiscussion)
CREATE TABLE discussion_participant (
    user_id        BIGINT NOT NULL REFERENCES users (id)      ON DELETE CASCADE,
    discussion_id  BIGINT NOT NULL REFERENCES discussion (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, discussion_id)
);

CREATE INDEX idx_discussion_participant_discussion ON discussion_participant (discussion_id);


-- ---------------------------------------------------------------------
-- Messages
-- ---------------------------------------------------------------------
CREATE TABLE message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id  BIGINT      NOT NULL REFERENCES discussion (id) ON DELETE CASCADE,
    author_id      BIGINT      NOT NULL REFERENCES users (id)      ON DELETE CASCADE,
    content        TEXT        NOT NULL,
    sent_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_message_discussion ON message (discussion_id, sent_at);


-- ---------------------------------------------------------------------
-- Proposals made inside a discussion
-- ---------------------------------------------------------------------
CREATE TABLE proposal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id  BIGINT      NOT NULL REFERENCES discussion (id) ON DELETE CASCADE,
    author_id      BIGINT      NOT NULL REFERENCES users (id)      ON DELETE CASCADE,
    status         VARCHAR(20) NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'accepted', 'rejected')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_proposal_discussion ON proposal (discussion_id);


-- ---------------------------------------------------------------------
-- Time transactions (credit one user, debit the other)
-- ---------------------------------------------------------------------
CREATE TABLE time_transaction (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id       BIGINT      NOT NULL UNIQUE REFERENCES proposal (id) ON DELETE CASCADE,
    status            VARCHAR(20) NOT NULL
                      CHECK (status IN ('rejected', 'validated')),
    duration_minutes  INTEGER     NOT NULL CHECK (duration_minutes > 0),
    creditor_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    debtor_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    completed         BOOLEAN     NOT NULL DEFAULT FALSE,
    completed_at      TIMESTAMPTZ,
    CHECK (creditor_id <> debtor_id),
    CHECK (completed = (completed_at IS NOT NULL))
);

CREATE INDEX idx_time_transaction_creditor ON time_transaction (creditor_id);
CREATE INDEX idx_time_transaction_debtor   ON time_transaction (debtor_id);
